def android_escape(text):
    return escape(text).replace("'", "\\'").replace('"', '\\"')


def main():
    for index, lang in enumerate(LANGS):
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by tools/i18n/strings.py — edit the table there, not this file. -->",
                 "<resources>"]
        for key, values in STRINGS.items():
            assert len(values) == len(LANGS), key
            lines.append('    <string name="%s">%s</string>' % (key, android_escape(values[index])))
        for key, per_lang in PLURALS.items():
            assert set(per_lang) == set(LANGS), key
            lines.append('    <plurals name="%s">' % key)
            for quantity, text in per_lang[lang].items():
                lines.append('        <item quantity="%s">%s</item>' % (quantity, android_escape(text)))
            lines.append("    </plurals>")
        lines.append("</resources>")
        folder = "values" if lang == "en" else "values-" + lang
        path = os.path.join(ROOT, "app", "src", "main", "res", folder, "strings.xml")
        with open(path, "w", encoding="utf-8") as out:
            out.write("\n".join(lines) + "\n")
        print(path)


if __name__ == "__main__":
    main()
